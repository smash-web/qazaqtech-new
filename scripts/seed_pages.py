def main() -> None:
    base = os.environ["CMS_URL"].rstrip("/") + "/api"
    login = requests.post(f"{base}/users/login", json={"email": os.environ["ADMIN_EMAIL"],
                                                      "password": os.environ["ADMIN_PASSWORD"]}, timeout=30)
    login.raise_for_status()
    h = {"Authorization": f"JWT {login.json()['token']}"}
    for p in PAGES:
        found = requests.get(f"{base}/pages", params={"where[slug][equals]": p["slug"], "limit": 1}, headers=h, timeout=30).json()
        if found.get("docs"):
            print("exists", p["slug"])
            continue
        r = requests.post(f"{base}/pages", headers=h, timeout=30, json={
            "title": p["title"], "slug": p["slug"], "summary": p["summary"], "order": p["order"],
            "showInFooter": True, "content": markdown_to_lexical(p["body"]),
        })
        print(p["slug"], r.status_code, "" if r.ok else r.text[:300])


if __name__ == "__main__":
    main()
