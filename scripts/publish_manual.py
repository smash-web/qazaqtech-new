def main() -> None:
    base = os.environ["CMS_URL"].rstrip("/") + "/api"
    s = requests.Session()
    s.headers.update({"Authorization": f"users API-Key {os.environ['CMS_API_KEY']}"})
    for a in ARTICLES:
        payload = {
            "title": a["title"],
            "slug": slugify(a["title"]),
            "excerpt": a["excerpt"],
            "content": markdown_to_lexical(a["body"]),
            "category": a["category"],
            "tags": [{"tag": t} for t in a["tags"]],
            "meta": {"title": a["title"][:70], "description": a["seo"][:170]},
            "status": "published",
            "aiGenerated": True,
            "qaNotes": "",
        }
        r = s.patch(f"{base}/articles/{a['id']}", json=payload, timeout=60)
        print(a["id"], r.status_code, r.json().get("doc", {}).get("slug") if r.ok else r.text[:400])


if __name__ == "__main__":
    main()
